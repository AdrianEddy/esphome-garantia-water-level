"""Generate the ETS application XML (OpenKNXproducer input) from spec.py.

OpenKNXproducer fills in the %AID%-style placeholders and signs the .knxprod with the local ETS installation
(see build.sh). Based on knx-rgbic's gen_xml.py; adds 16-bit parameters, enumerations and conditional
parameters/objects (<choose> on a Yes/No parameter).
"""
import pathlib
from xml.sax.saxutils import quoteattr as q
import spec as S

HERE = pathlib.Path(__file__).parent
OUT = HERE / "garantia-knx.xml"
SEG = "%AID%_RS-04-00000"


def flags(f: str) -> str:
    def e(c): return "Enabled" if c in f else "Disabled"
    return (f'ReadFlag="{e("R")}" WriteFlag="{e("W")}" CommunicationFlag="{e("C")}" '
            f'TransmitFlag="{e("T")}" UpdateFlag="{e("U")}" ReadOnInitFlag="{e("I")}"')


def ptype_id(name): return f"%AID%_PT-{name}"   # ETS: no "-" inside the name part


def main():
    ptypes, params, prefs, kos, korefs = [], [], [], [], []
    seen_types = set()
    pref_of, koref_of = {}, {}

    def add_type(name, xml):
        if name not in seen_types:
            seen_types.add(name)
            ptypes.append(f'<ParameterType Id="{ptype_id(name)}" Name="{name}">{xml}</ParameterType>')
        return ptype_id(name)

    def enum_type(name, bits, values):
        en = "".join(f'<Enumeration Text={q(t)} Value="{v}" Id="{ptype_id(name)}_EN-{v}" />' for v, t in values)
        return add_type(name, f'<TypeRestriction Base="Value" SizeInBit="{bits}">{en}</TypeRestriction>')

    for pnum, (name, off, bits, dflt, lo, hi, text, block, enum, when) in enumerate(S.PARAMS, 1):
        if enum:
            pt = enum_type(enum, bits, S.ENUMS[enum])
        elif (lo, hi) == (0, 1):
            pt = enum_type("YesNo", bits, [(0, "No"), (1, "Yes")])
        else:
            tn = f"U{bits}x{lo}x{hi}"
            pt = add_type(tn, f'<TypeNumber SizeInBit="{bits}" Type="unsignedInt" minInclusive="{lo}" maxInclusive="{hi}" />')
        pid = f"%AID%_P-{pnum}"
        params.append(f'<Parameter Id="{pid}" Name={q(name)} ParameterType="{pt}" Text={q(text)} Value="{dflt}">'
                      f'<Memory CodeSegment="{SEG}" Offset="{off}" BitOffset="0" /></Parameter>')
        rid = f"{pid}_R-{pnum}"
        prefs.append(f'<ParameterRef Id="{rid}" RefId="{pid}" />')
        pref_of[name] = rid

    for name, num, text, dpt, size, fl, block, when in S.KOS:
        oid = f"%AID%_O-{num}"
        kos.append(f'<ComObject Id="{oid}" Name={q(name)} Text={q(text)} Number="{num}" FunctionText="Tank" '
                   f'ObjectSize="{size}" {flags(fl)} DatapointType="{dpt}" />')
        korefs.append(f'<ComObjectRef Id="{oid}_R-{num}" RefId="{oid}" />')
        koref_of[name] = f"{oid}_R-{num}"

    # ---- UI: one ParameterBlock per spec block. Items keep the spec's order; items with a "when" are placed
    # in a <choose> right after the parameter that controls them. ----
    def item_param(name): return f'<ParameterRefRef RefId="{pref_of[name]}" />'
    def item_ko(name): return f'<ComObjectRefRef RefId="{koref_of[name]}" />'

    dependents = {}   # (controller, value) -> [xml]
    for p in S.PARAMS:
        if p[9]:
            dependents.setdefault(p[9], []).append(item_param(p[0]))
    for k in S.KOS:
        if k[7]:
            dependents.setdefault(k[7], []).append(item_ko(k[0]))

    blocks = []
    for bi, (key, title, note) in enumerate(S.BLOCKS, 1):
        items = [f'<ParameterSeparator Id="%AID%_PS-{bi}" Text={q(note)} />']
        for p in S.PARAMS:
            if p[7] != key or p[9]:
                continue
            items.append(item_param(p[0]))
            for (ctl, val), deps in dependents.items():
                if ctl == p[0]:
                    items.append(f'<choose ParamRefId="{pref_of[ctl]}"><when test="{val}">' + "".join(deps) +
                                 "</when></choose>")
        for k in S.KOS:
            if k[6] == key and not k[7]:
                items.append(item_ko(k[0]))
        blocks.append(f'<ParameterBlock Id="%AID%_PB-{bi}" Name={q(key)} Text={q(title)}>' + "".join(items) +
                      "</ParameterBlock>")

    xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by firmware/knxprod/gen_xml.py from spec.py. Don't edit by hand. -->
<KNX xmlns="http://knx.org/xml/project/20" CreatedBy="KNX MT" ToolVersion="5.1.255.16695">
  <ManufacturerData>
    <Manufacturer RefId="M-{S.MANUFACTURER:04X}">
      <Catalog>
        <CatalogSection Id="M-{S.MANUFACTURER:04X}_CS-1" Name="Devices" Number="1" DefaultLanguage="en-US">
          <CatalogItem Id="%CatalogItemId%" Name={q(S.PRODUCT_NAME)} Number="1" ProductRefId="%ProductId%" Hardware2ProgramRefId="%Hardware2ProgramId%" DefaultLanguage="en-US" />
        </CatalogSection>
      </Catalog>
      <ApplicationPrograms>
        <ApplicationProgram Id="%AID%" ApplicationNumber="{S.APP_NUMBER}" ApplicationVersion="{S.APP_VERSION}" ReplacesVersions="{" ".join(str(v) for v in getattr(S, "REPLACES_VERSIONS", ())) or "0"}" ProgramType="ApplicationProgram" MaskVersion="MV-07B0" Name={q(S.APP_NAME)} LoadProcedureStyle="MergedProcedure" PeiType="0" DefaultLanguage="en-US" DynamicTableManagement="false" Linkable="true" MinEtsVersion="5.0">
          <Static>
            <Code>
              <RelativeSegment Id="{SEG}" Name="Parameters" Offset="0" Size="{S.PARAM_SIZE}" LoadStateMachine="4" />
            </Code>
            <ParameterTypes>{"".join(ptypes)}</ParameterTypes>
            <Parameters>{"".join(params)}</Parameters>
            <ParameterRefs>{"".join(prefs)}</ParameterRefs>
            <ComObjectTable>{"".join(kos)}</ComObjectTable>
            <ComObjectRefs>{"".join(korefs)}</ComObjectRefs>
            <AddressTable MaxEntries="255" />
            <AssociationTable MaxEntries="255" />
            <LoadProcedures>
              <LoadProcedure MergeId="2">
                <LdCtrlRelSegment LsmIdx="4" Size="{S.PARAM_SIZE}" Mode="1" Fill="0" AppliesTo="full" />
                <LdCtrlRelSegment LsmIdx="4" Size="{S.PARAM_SIZE}" Mode="0" Fill="0" AppliesTo="par" />
              </LoadProcedure>
              <LoadProcedure MergeId="4">
                <LdCtrlWriteRelMem ObjIdx="4" Offset="0" Size="{S.PARAM_SIZE}" Verify="true" AppliesTo="full,par" />
              </LoadProcedure>
              <LoadProcedure MergeId="7">
                <LdCtrlLoadImageProp ObjIdx="1" PropId="27" />
                <LdCtrlLoadImageProp ObjIdx="2" PropId="27" />
                <LdCtrlLoadImageProp ObjIdx="3" PropId="27" />
                <LdCtrlLoadImageProp ObjIdx="4" PropId="27" />
              </LoadProcedure>
            </LoadProcedures>
            <Options />
          </Static>
          <Dynamic>
            <ChannelIndependentBlock>{"".join(blocks)}</ChannelIndependentBlock>
          </Dynamic>
        </ApplicationProgram>
      </ApplicationPrograms>
      <Hardware>
        <Hardware Id="%HardwareId%" Name={q(S.PRODUCT_NAME)} SerialNumber="{S.HARDWARE_SERIAL}" VersionNumber="1" BusCurrent="{S.BUS_CURRENT_MA}" HasIndividualAddress="true" HasApplicationProgram="true">
          <Products>
            <Product Id="%ProductId%" Text={q(S.PRODUCT_NAME)} OrderNumber={q(S.ORDER_NUMBER)} IsRailMounted="false" DefaultLanguage="en-US">
              <RegistrationInfo RegistrationStatus="Registered" />
            </Product>
          </Products>
          <Hardware2Programs>
            <Hardware2Program Id="%Hardware2ProgramId%" MediumTypes="MT-0">
              <ApplicationProgramRef RefId="%AID%" />
              <RegistrationInfo RegistrationStatus="Registered" RegistrationNumber="0001/%HardwareVersionEncoded%1" />
            </Hardware2Program>
          </Hardware2Programs>
        </Hardware>
      </Hardware>
    </Manufacturer>
  </ManufacturerData>
</KNX>
'''
    OUT.write_text(xml, encoding="utf-8", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
